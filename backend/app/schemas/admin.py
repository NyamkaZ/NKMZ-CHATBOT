from typing import Optional, List
from pydantic import BaseModel
from uuid import UUID
from datetime import datetime


class SystemStatus(BaseModel):
    status: str
    postgres: str
    redis: str
    ollama: str
    ollama_model: Optional[str] = None
    uptime_seconds: Optional[float] = None


class ModelHealth(BaseModel):
    name: str
    available: bool
    size: Optional[str] = None
    details: Optional[dict] = None


class AnalyticsSummary(BaseModel):
    total_users: int
    active_users_today: int
    total_chats: int
    total_messages: int
    messages_today: int
    guest_conversions: int


class UsageDay(BaseModel):
    date: str  # YYYY-MM-DD (UTC)
    answers: int = 0
    prompt_tokens: int = 0
    output_tokens: int = 0


class UsageByUser(BaseModel):
    email: Optional[str] = None  # None = guests
    answers: int
    prompt_tokens: int
    output_tokens: int


class UsageReport(BaseModel):
    days: int
    answers: int            # answers generated by the model
    direct_answers: int     # FAQ answers served without the model
    prompt_tokens: int
    output_tokens: int
    model_seconds: float    # total model time
    avg_seconds: Optional[float] = None
    tokens_per_second: Optional[float] = None
    daily: List[UsageDay]
    top_users: List[UsageByUser]


class UsageLimitUpdate(BaseModel):
    daily_message_limit: int


class UserAdminOut(BaseModel):
    id: UUID
    email: Optional[str]
    full_name: Optional[str]
    role: str
    is_active: bool
    is_guest: bool
    daily_message_count: int
    created_at: datetime
    chat_count: int = 0
